import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { main } from "../src/main.js";
import { copyValid, createRemotes, initProject, write, type TestRemotes } from "./helpers/remotes.js";

let remotes: TestRemotes;

const pack = (name: string, extra: Record<string, unknown> = {}) => JSON.stringify({ name, ...extra });
const skillMd = (name: string, desc = "A skill.") => `---\nname: ${name}\ndescription: ${desc}\nmetadata:\n  internal: "true"\n---\n\n# ${name}\n`;

beforeAll(() => {
  remotes = createRemotes();
  remotes.add("acme/skills", [
    { apply: copyValid, tag: "v1.0.0" },
    { apply: (w) => write(w, "src/skills/plan_code/SKILL.md", readFileSync(join(w, "src/skills/plan_code/SKILL.md"), "utf8") + "\nv1.1 change\n"), tag: "v1.1.0" },
    { apply: (w) => write(w, "src/skills/review/extra.md", "beta\n"), tag: "v2.0.0-beta.1" },
  ]);
  remotes.add("acme/other", [
    { apply: (w) => { write(w, "skillpack.pack.json", pack("other")); write(w, "src/skills/review/SKILL.md", skillMd("review", "Other review.")); write(w, "src/skills/other_thing/SKILL.md", skillMd("other_thing")); }, tag: "v1.0.0" },
  ]);
  remotes.add("acme/clash", [
    { apply: (w) => { write(w, "skillpack.pack.json", pack("tpack")); write(w, "src/skills/review/SKILL.md", skillMd("review")); } },
  ]);
  remotes.add("acme/ocnly", [
    { apply: (w) => { write(w, "skillpack.pack.json", pack("ocnly", { harnesses: ["opencode"] })); write(w, "src/skills/one/SKILL.md", skillMd("one")); } },
  ]);
  remotes.add("acme/future", [
    { apply: (w) => { write(w, "skillpack.pack.json", pack("future", { cli: ">=99.0.0" })); write(w, "src/skills/one/SKILL.md", skillMd("one")); } },
  ]);
  remotes.add("acme/nomanifest", [{ apply: (w) => write(w, "skills/one/SKILL.md", skillMd("one")) }]);
});

async function cli(project: string, args: string[], detected: ("opencode" | "codex")[] = []) {
  let out = "";
  let err = "";
  const code = await main(args, {
    cwd: project,
    env: remotes.env,
    detectHarnesses: () => detected,
    stdout: (t) => (out += t),
    stderr: (t) => (err += t),
    color: false,
  });
  return { code, out, err };
}
const readJson = (project: string, file: string) => JSON.parse(readFileSync(join(project, file), "utf8"));
const snapshot = (dir: string): string[] => {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      if (e.name === ".git") continue;
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else out.push(p.slice(dir.length) + ":" + readFileSync(p).length);
    }
  };
  walk(dir);
  return out.sort();
};

describe("add", () => {
  it("installs the latest tag with prefixed skills, lock, agents without models, and an exclude block", async () => {
    const project = initProject();
    const r = await cli(project, ["add", "acme/skills", "-a", "opencode,codex", "-y"]);
    expect(r.err).toBe("");
    expect(r.code).toBe(0);

    const config = readJson(project, "skillpack.json");
    expect(config.packs["https://github.com/acme/skills"]).toEqual({
      version: "^1.1.0",
      harnesses: ["opencode", "codex"],
      skills: "*",
      agents: {
        author: { opencode: "generate", codex: "generate" },
        code_lead: { opencode: "generate", codex: "generate" },
        scout: { opencode: "generate", codex: "generate" },
      },
    });

    const lock = readJson(project, "skillpack-lock.json");
    const entry = lock.packs["https://github.com/acme/skills"];
    expect(lock.cli).toBe("0.1.0");
    expect(entry.version).toBe("v1.1.0");
    expect(entry.commit).toMatch(/^[0-9a-f]{40}$/);
    expect(Object.keys(entry.skills)).toEqual([".agents/skills/tpack-plan-code", ".agents/skills/tpack-review"]);
    expect(Object.values(entry.skills)[0]).toMatch(/^sha256-[0-9a-f]{64}$/);

    expect(readFileSync(join(project, ".agents/skills/tpack-plan-code/SKILL.md"), "utf8")).toContain("v1.1 change");
    expect(readFileSync(join(project, ".agents/skills/tpack-review/SKILL.md"), "utf8")).toContain("`tpack-scout`");
    const author = readFileSync(join(project, ".opencode/agents/tpack-author.md"), "utf8");
    expect(author).toContain("# generated by skillpack from https://github.com/acme/skills@v1.1.0 src/agents/author/");
    expect(author).not.toMatch(/^model:/m);
    expect(author).not.toContain("# model:");
    expect(author).toContain("# binding: generate; model: none; effort: default");
    const codex = readFileSync(join(project, ".codex/agents/tpack-author.toml"), "utf8");
    expect(codex).not.toMatch(/^model/m);
    expect(codex).not.toContain("model_reasoning_effort");
    expect(existsSync(join(project, "skillpack.models.json"))).toBe(false);

    const exclude = readFileSync(join(project, ".git/info/exclude"), "utf8");
    expect(exclude).toContain("# >>> skillpack (managed; do not edit)");
    expect(exclude).toContain("/.opencode/agents/tpack-author.md");
    expect(exclude).toContain("/.codex/agents/tpack-scout.toml");
    expect(exclude).not.toContain("models");

    expect(r.out).toContain("tpack-review");
    expect(r.out).toContain("Executable scripts");
    expect(r.out).toContain(".agents/skills/tpack-review/scripts/check.sh");
    expect(r.out).toContain("model matching isn't available yet");
    expect(r.out).toMatch(/unenforced\s+author \(Codex\): \d+ restrictions not enforced/);
    expect(r.out).toContain("Commit: skillpack.json, skillpack-lock.json, .agents/skills/tpack-*");
    expect(r.out).toContain("v1.1.0 (^1.1.0)");
    expect(r.out).toContain("Commit: skillpack.json, skillpack-lock.json, .agents/skills/tpack-*");
    expect(entry.branch).toBeNull();
    const again = await cli(project, ["add", "acme/skills", "-a", "opencode,codex", "-y"]);
    expect(again.out).not.toContain("Commit:"); // nothing committed changed
  });

  it("prints a note instead of prompting without -y", async () => {
    const project = initProject();
    const r = await cli(project, ["add", "acme/skills", "-a", "opencode"]);
    expect(r.code).toBe(0);
    expect(r.out).toContain("Interactive selection isn't available yet");
  });

  it("@1.0.0 pins an exact version", async () => {
    const project = initProject();
    expect((await cli(project, ["add", "acme/skills@1.0.0", "-a", "codex", "-y"])).code).toBe(0);
    expect(readJson(project, "skillpack.json").packs["https://github.com/acme/skills"].version).toBe("1.0.0");
    expect(readJson(project, "skillpack-lock.json").packs["https://github.com/acme/skills"].version).toBe("v1.0.0");
    expect(readFileSync(join(project, ".agents/skills/tpack-plan-code/SKILL.md"), "utf8")).not.toContain("v1.1 change");
    expect(existsSync(join(project, ".opencode"))).toBe(false);
  });

  it("branch versions lock a commit and no tag", async () => {
    const project = initProject();
    expect((await cli(project, ["add", "acme/skills@main", "-a", "codex", "-y"])).code).toBe(0);
    expect(readJson(project, "skillpack.json").packs["https://github.com/acme/skills"].version).toBe("main");
    expect(readJson(project, "skillpack-lock.json").packs["https://github.com/acme/skills"].version).toBeNull();
  });

  it("--dry-run writes nothing but describes everything", async () => {
    const project = initProject();
    const before = snapshot(project);
    const excludeBefore = readFileSync(join(project, ".git/info/exclude"), "utf8");
    const r = await cli(project, ["add", "acme/skills", "-a", "opencode,codex", "--dry-run"]);
    expect(r.code).toBe(0);
    expect(r.out).toContain("Would change");
    expect(r.out).toContain("+ skillpack.json  (config)");
    expect(r.out).toContain("+ skillpack-lock.json  (lock)");
    expect(r.out).toContain("+ .agents/skills/tpack-review  (skill)");
    expect(r.out).toContain("+ .opencode/agents/tpack-author.md  (agent)");
    expect(r.out).toContain("~ .git/info/exclude  (exclude)");
    expect(r.out).toContain("dry run");
    expect(snapshot(project)).toEqual(before);
    expect(readFileSync(join(project, ".git/info/exclude"), "utf8")).toBe(excludeBefore);
  });

  it("a second pack with another scope installs alongside; skillpack.json keeps both", async () => {
    const project = initProject();
    await cli(project, ["add", "acme/skills", "-a", "opencode", "-y"]);
    const r = await cli(project, ["add", "acme/other", "-a", "opencode", "-y"]);
    expect(r.code).toBe(0);
    expect(Object.keys(readJson(project, "skillpack.json").packs)).toEqual(["https://github.com/acme/skills", "https://github.com/acme/other"]);
    expect(readdirSync(join(project, ".agents/skills")).sort()).toEqual(["other-other-thing", "other-review", "tpack-plan-code", "tpack-review"]);
    expect(Object.keys(readJson(project, "skillpack-lock.json").packs)).toHaveLength(2);
  });

  it("fails on a scope or name collision without writing anything", async () => {
    const project = initProject();
    await cli(project, ["add", "acme/skills", "-a", "opencode", "-y"]);
    const before = snapshot(project);
    const r = await cli(project, ["add", "acme/clash", "-a", "opencode", "-y"]);
    expect(r.code).toBe(1);
    expect(r.err).toContain("already installed by https://github.com/acme/skills");
    expect(snapshot(project)).toEqual(before);
    // --as resolves it
    const ok = await cli(project, ["add", "acme/clash", "-a", "opencode", "-y", "--as", "clash"]);
    expect(ok.code).toBe(0);
    expect(readJson(project, "skillpack.json").packs["https://github.com/acme/clash"].scope).toBe("clash");
    expect(existsSync(join(project, ".agents/skills/clash-review"))).toBe(true);
    // same explicit scope as an existing pack is a conflict
    expect((await cli(project, ["add", "acme/other", "-a", "opencode", "-y", "--as", "clash"])).err).toContain('scope "clash" is already used');
  });

  it("--as is saved as scope only when given", async () => {
    const project = initProject();
    expect((await cli(project, ["add", "acme/skills", "-a", "opencode", "-y"])).code).toBe(0);
    expect(readJson(project, "skillpack.json").packs["https://github.com/acme/skills"].scope).toBeUndefined();
    const other = initProject();
    expect((await cli(other, ["add", "acme/skills", "-a", "opencode", "-y", "--as", "my_scope"])).code).toBe(0);
    expect(readJson(other, "skillpack.json").packs["https://github.com/acme/skills"].scope).toBe("my_scope");
    expect(existsSync(join(other, ".agents/skills/my-scope-review"))).toBe(true);
    expect(existsSync(join(other, ".opencode/agents/my-scope-author.md"))).toBe(true);
  });

  it("a foreign folder blocks without --force and is overwritten with it", async () => {
    const project = initProject();
    mkdirSync(join(project, ".agents/skills/tpack-review"), { recursive: true });
    writeFileSync(join(project, ".agents/skills/tpack-review/SKILL.md"), "mine\n");
    const before = snapshot(project);
    const r = await cli(project, ["add", "acme/skills", "-a", "opencode", "-y"]);
    expect(r.code).toBe(1);
    expect(r.err).toContain(".agents/skills/tpack-review (not installed by skillpack)");
    expect(r.err).toContain("--force");
    expect(snapshot(project)).toEqual(before);
    const f = await cli(project, ["add", "acme/skills", "-a", "opencode", "-y", "--force"]);
    expect(f.code).toBe(0);
    expect(readFileSync(join(project, ".agents/skills/tpack-review/SKILL.md"), "utf8")).toContain("name: tpack-review");
  });

  it("keeps edited owned folders and agents without --force", async () => {
    const project = initProject();
    await cli(project, ["add", "acme/skills", "-a", "opencode", "-y"]);
    const skill = join(project, ".agents/skills/tpack-review/SKILL.md");
    writeFileSync(skill, readFileSync(skill, "utf8") + "\nlocal edit\n");
    const agent = join(project, ".opencode/agents/tpack-scout.md");
    writeFileSync(agent, readFileSync(agent, "utf8") + "\nlocal edit\n");
    const r = await cli(project, ["add", "acme/skills@1.0.0", "-a", "opencode", "-y"]);
    expect(r.code).toBe(1);
    expect(r.err).toContain(".agents/skills/tpack-review (edited since install)");
    expect(r.err).toContain(".opencode/agents/tpack-scout.md (edited since install)");
    expect(readFileSync(skill, "utf8")).toContain("local edit");
    expect(readJson(project, "skillpack.json").packs["https://github.com/acme/skills"].version).toBe("^1.1.0");
    expect((await cli(project, ["add", "acme/skills@1.0.0", "-a", "opencode", "-y", "--force"])).code).toBe(0);
    expect(readFileSync(skill, "utf8")).not.toContain("local edit");
  });

  it("re-adding replaces the entry and drops skills no longer selected", async () => {
    const project = initProject();
    await cli(project, ["add", "acme/skills", "-a", "opencode", "-y"]);
    const r = await cli(project, ["add", "acme/skills", "-a", "opencode", "-y", "-s", "review"]);
    expect(r.code).toBe(0);
    expect(readdirSync(join(project, ".agents/skills"))).toEqual(["tpack-review"]);
    expect(readJson(project, "skillpack.json").packs["https://github.com/acme/skills"].skills).toEqual(["review"]);
    expect(Object.keys(readJson(project, "skillpack-lock.json").packs["https://github.com/acme/skills"].skills)).toEqual([".agents/skills/tpack-review"]);
  });

  it("-s selects a subset and rejects unknown skills", async () => {
    const project = initProject();
    expect((await cli(project, ["add", "acme/skills", "-a", "opencode", "-y", "-s", "plan_code"])).code).toBe(0);
    expect(readdirSync(join(project, ".agents/skills"))).toEqual(["tpack-plan-code"]);
    const bad = await cli(initProject(), ["add", "acme/skills", "-a", "opencode", "-y", "-s", "nope"]);
    expect(bad.code).toBe(2);
    expect(bad.err).toContain('no skill "nope"');
  });

  it("--agent none binds everything to none and writes no agent files or exclude block", async () => {
    const project = initProject();
    const r = await cli(project, ["add", "acme/skills", "-a", "opencode,codex", "-y", "--agent", "none"]);
    expect(r.code).toBe(0);
    const agents = readJson(project, "skillpack.json").packs["https://github.com/acme/skills"].agents;
    expect(agents.scout).toEqual({ opencode: "none", codex: "none" });
    expect(existsSync(join(project, ".opencode"))).toBe(false);
    expect(existsSync(join(project, ".codex"))).toBe(false);
    expect(readFileSync(join(project, ".git/info/exclude"), "utf8")).not.toContain("skillpack");
    expect(readFileSync(join(project, ".agents/skills/tpack-review/SKILL.md"), "utf8")).toContain("a helper subagent");
    expect(r.out).not.toContain("model matching");
  });

  it("respects the manifest's harnesses", async () => {
    const project = initProject();
    const bad = await cli(project, ["add", "acme/ocnly", "-a", "codex", "-y"]);
    expect(bad.code).toBe(2);
    expect(bad.err).toContain("doesn't support the harness");
    expect(existsSync(join(project, "skillpack.json"))).toBe(false);
    expect((await cli(project, ["add", "acme/ocnly", "-a", "*", "-y"])).code).toBe(0);
    expect(readJson(project, "skillpack.json").packs["https://github.com/acme/ocnly"].harnesses).toEqual(["opencode"]);
  });

  it("uses detected harnesses, and asks for -a when there are none", async () => {
    const project = initProject();
    const none = await cli(project, ["add", "acme/skills", "-y"]);
    expect(none.code).toBe(1);
    expect(none.err).toContain("pass -a");
    expect((await cli(project, ["add", "acme/skills", "-y"], ["codex"])).code).toBe(0);
    expect(readJson(project, "skillpack.json").packs["https://github.com/acme/skills"].harnesses).toEqual(["codex"]);
    const oc = initProject();
    expect((await cli(oc, ["add", "acme/ocnly", "-y"], ["codex", "opencode"])).code).toBe(0);
    expect(readJson(oc, "skillpack.json").packs["https://github.com/acme/ocnly"].harnesses).toEqual(["opencode"]);
  });

  it("fails when the pack's cli range excludes this version", async () => {
    const project = initProject();
    const r = await cli(project, ["add", "acme/future", "-a", "opencode", "-y"]);
    expect(r.code).toBe(1);
    expect(r.out).toContain("this pack needs skillpack >=99.0.0");
    expect(snapshot(project)).toEqual([]);
  });

  it("fails clearly for packs without a manifest and unknown versions/sources", async () => {
    const project = initProject();
    const nm = await cli(project, ["add", "acme/nomanifest", "-a", "opencode", "-y"]);
    expect(nm.code).toBe(1);
    expect(nm.err).toContain("aren't supported yet");
    const v = await cli(project, ["add", "acme/skills@9.9.9", "-a", "opencode", "-y"]);
    expect(v.code).toBe(1);
    expect(v.err).toContain("No version");
    expect((await cli(project, ["add", "./local", "-y"])).code).toBe(2);
    expect((await cli(project, ["add"])).code).toBe(2);
    expect(snapshot(project)).toEqual([]);
  });

  it("warns about skills already installed by npx skills and never removes them", async () => {
    const project = initProject();
    write(project, "skills-lock.json", JSON.stringify({ skills: { "plan-code": { source: "acme/skills" } } }));
    write(project, ".agents/skills/review/SKILL.md", "---\nname: review\ndescription: Skill review for tests.\n---\n");
    const r = await cli(project, ["add", "acme/skills", "-a", "opencode", "-y"]);
    expect(r.code).toBe(0);
    expect(r.out).toContain("npx skills remove plan-code review");
    expect(existsSync(join(project, ".agents/skills/review/SKILL.md"))).toBe(true);
  });

  it("--json prints a machine-readable result", async () => {
    const project = initProject();
    const r = await cli(project, ["add", "acme/skills", "-a", "opencode", "-y", "--json", "--dry-run"]);
    const j = JSON.parse(r.out);
    expect(j).toMatchObject({ ok: true, dryRun: true, source: "https://github.com/acme/skills", version: "v1.1.0", requested: "^1.1.0", scope: "tpack" });
    expect(j.changes.some((c: { path: string }) => c.path === "skillpack.json")).toBe(true);
    expect(existsSync(join(project, "skillpack.json"))).toBe(false);
  });

  it("outside a git repository it prints the paths to keep out of git", async () => {
    const { mkdtempSync, realpathSync } = await import("node:fs");
    const { tmpdir } = await import("node:os");
    const project = realpathSync(mkdtempSync(join(tmpdir(), "sp-nogit-")));
    const r = await cli(project, ["add", "acme/skills", "-a", "opencode", "-y"]);
    expect(r.code).toBe(0);
    expect(r.out).toContain("Not a git repository");
    expect(r.out).toContain("/.opencode/agents/tpack-author.md");
  });
});
