import { createHash } from "node:crypto";

export interface AgentHeader {
  source: string;
  version: string;
  agent: string;
  /** "generate" (only generated agents carry a header). */
  binding: string;
  /** Concrete model, else the first requested name, else "none". */
  model: string;
  /** Requested effort, or "default". */
  effort: string;
}

export interface ParsedAgentHeader extends AgentHeader {
  hash: string;
  /** Offset in the content where the bytes covered by the hash start. */
  bodyStart: number;
}

export const hashAgentBody = (body: string): string => `sha256-${createHash("sha256").update(body, "utf8").digest("hex")}`;

/** The three header comment lines (each ending in a newline) for the given content after them. */
export function buildAgentHeader(h: AgentHeader, body: string): string {
  return (
    `# generated by skillpack from ${h.source}@${h.version} src/agents/${h.agent}/ — do not edit; change with \`skillpack configure\`\n` +
    `# binding: ${h.binding}; model: ${h.model}; effort: ${h.effort}\n` +
    `# hash: ${hashAgentBody(body)}\n`
  );
}

const LINE1 = /^# generated by skillpack from (\S+)@(\S+) src\/agents\/(\S+)\/ — do not edit; change with `skillpack configure`$/;

/** Reads the header of a generated agent file (OpenCode: right after the opening `---`; Codex: at the top). */
export function parseAgentHeader(content: string): ParsedAgentHeader | null {
  const prefix = content.startsWith("---\n") ? 4 : 0;
  const lines = content.slice(prefix).split("\n", 3);
  if (lines.length < 3) return null;
  const m = LINE1.exec(lines[0]!);
  const b = /^# binding: ([^;]+); model: (.+); effort: (.+)$/.exec(lines[1]!);
  const h = /^# hash: (sha256-[0-9a-f]{64})$/.exec(lines[2]!);
  if (!m || !b || !h) return null;
  const bodyStart = prefix + lines.reduce((n, l) => n + l.length + 1, 0);
  return { source: m[1]!, version: m[2]!, agent: m[3]!, binding: b[1]!, model: b[2]!, effort: b[3]!, hash: h[1]!, bodyStart };
}

/** True when the file has a header and nothing after it was edited. */
export function verifyAgentHash(content: string): boolean {
  const p = parseAgentHeader(content);
  return p !== null && hashAgentBody(content.slice(p.bodyStart)) === p.hash;
}
